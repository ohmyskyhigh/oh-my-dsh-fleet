import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const files = ['fleet-model.js', 'fleet-workspace-nav.js', 'fleet-theme.js', 'fleet-ui.js', 'fleet-locale.js', 'fleet-draft-client.js'];
const ownedModuleImports = {
  'fleet-ui.js': ["import { TICKET_STATUSES } from './fleet-model.js';", "import { projectTicket, validatePlan, graphLevels, isIncompatibleDraft, readableTitle, stagePlanView, effectiveSeriesTiming, isUtcInstant, seriesRecurrence, seriesScheduledAt } from './fleet-model.js';"],
  'fleet-draft-client.js': ["import { fleetResponseError } from './fleet-locale.js';", "import { TICKET_STATUSES } from './fleet-model.js';"]
};
const client = await readFile(new URL('packages/fleet-shell/src/fleet-client.js', root), 'utf8');
const imports = [
  "import { mountWorkspaceDashboardLinks } from './fleet-workspace-nav.js';",
  "import { fleetStyles } from './fleet-theme.js';",
  "import { createFleetViews } from './fleet-ui.js';",
  "import { createFleetLanguage, fleetDictionaries, fleetTranslator, fleetResponseError, fleetErrorRecord, fleetErrorText } from './fleet-locale.js';",
  "import { createFleetDraftClient } from './fleet-draft-client.js';",
  "import { projectTicket, isIncompatibleDraft } from './fleet-model.js';"
].join('\n');
assert.ok(client.startsWith(imports), 'Client imports must match owned modules');
const fleet = client.slice(imports.length).trimStart();
assert.equal((fleet.match(/^export function createFleetPlugin\(require\) \{/gm) ?? []).length, 1, 'Client must expose one owned plugin factory');
const modules = await Promise.all(files.map(async file => {
  let source = await readFile(new URL(`packages/fleet-shell/src/${file}`, root), 'utf8');
  for (const statement of ownedModuleImports[file] ?? []) {
    assert.equal(source.split(statement).length, 2, `${file} must import the exact shared contract once`);
    source = source.replace(statement, '');
  }
  assert.ok(!/^import\s/m.test(source), `${file} contains an unsupported module import`);
  return source;
}));
for (const source of [...modules, fleet]) assert.ok(!source.includes('@deepseek-ai/dsh-client-'), 'Fleet must not import or replace native UI internals');
const patch = await readFile(new URL('packages/fleet-shell/cordis.patch.yml', root), 'utf8');
assert.ok(!patch.includes('ui-workspace'), 'Fleet must leave the native Workspace plugin enabled');
const output = `// Generated by scripts/build-client.mjs; edit src/fleet-*.js, not this file.\n// Additive Fleet panels only; native Workspace and Chat stay owned by DSH.\nwindow.__ModuleLoader__.load({\n  id: '@dsh-fleet/shell',\n  factory(require) {\n${[...modules, fleet].map(source => source.replace(/^export /gm, '')).join('\n')}\n    return createFleetPlugin(require);\n  }\n});\n`;
const target = new URL('packages/fleet-shell/client.js', root);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'Generated client is stale');
else await writeFile(target, output);
console.log(JSON.stringify({status:'PASS',mode:process.argv.includes('--check')?'check':'build',nativeWorkspaceReplacement:false,modules:files.length+1,bytes:Buffer.byteLength(output)}));
